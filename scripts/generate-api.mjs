import {createHash} from 'node:crypto';
import {mkdir, readdir, readFile, writeFile, rm} from 'node:fs/promises';
import {resolve, relative, dirname} from 'node:path';
import {pathToFileURL} from 'node:url';
import {parseArgs} from 'node:util';
import openapiTS, {astToString} from 'openapi-typescript';

const root = resolve(import.meta.dirname, '..');
const {values} = parseArgs({options: {
  check: {type: 'boolean', default: false},
  'contracts-dir': {type: 'string'},
  'output-dir': {type: 'string'}
}});
const input = resolve(values['contracts-dir'] ?? resolve(root, 'packages/contracts/openapi'));
const output = resolve(values['output-dir'] ?? resolve(root, 'packages/api-client/src/generated'));

async function files(directory) {
  const result = [];
  for (const entry of await readdir(directory, {withFileTypes: true})) {
    const path = resolve(directory, entry.name);
    if (entry.isDirectory()) result.push(...await files(path));
    else if (entry.isFile()) result.push(path);
    else throw new Error('Unsupported generation input: ' + path);
  }
  return result.sort();
}

const inputs = (await files(input)).filter(path => /\.(yaml|yml|json)$/.test(path));
if (!inputs.length) throw new Error('No OpenAPI generation inputs');
const generated = new Map();
const hashes = {};
const aliases = [];
for (const [index, path] of inputs.entries()) {
  const name = relative(input, path).replaceAll('\\', '/');
  const filename = name.replace(/\.(yaml|yml|json)$/, '.ts').replaceAll('/', '__');
  if (generated.has(filename) || filename === 'index.ts') throw new Error('Generated name collision: ' + filename);
  hashes[name] = createHash('sha256').update(await readFile(path)).digest('hex');
  generated.set(filename, astToString(await openapiTS(pathToFileURL(path), {alphabetize: true})));
  aliases.push('import type {paths as P' + index + '} from "./' + filename.replace(/\.ts$/, '.js') + '";');
}
generated.set('inputs.json', JSON.stringify(hashes, null, 2) + '\n');
generated.set('index.ts', '// Generated by scripts/generate-api.mjs. Do not edit.\n' + aliases.join('\n')
  + '\ntype NonEmpty<P> = string extends keyof P ? Record<never, never> : P;\nexport type AllPaths = '
  + inputs.map((_, index) => 'NonEmpty<P' + index + '>').join(' & ') + ';\n');

if (values.check) {
  let actual;
  try {actual = await files(output);}
  catch (error) {
    if (error.code !== 'ENOENT') throw error;
    actual = [];
  }
  const differences = [];
  for (const [name, text] of generated) {
    let existing;
    try {existing = await readFile(resolve(output, name), 'utf8');}
    catch (error) {if (error.code !== 'ENOENT') throw error;}
    if (existing !== text) differences.push(name);
  }
  for (const path of actual) {
    const name = relative(output, path);
    if (!generated.has(name)) differences.push('unexpected ' + name);
  }
  if (differences.length) {
    console.error('Generated API is stale. Run npm run generate.\n' + differences.join('\n'));
    process.exitCode = 1;
  } else console.log('Generated API matches all ' + inputs.length + ' OpenAPI inputs and its output manifest.');
} else {
  await mkdir(output, {recursive: true});
  for (const path of await files(output)) {
    if (!generated.has(relative(output, path))) await rm(path);
  }
  for (const [name, text] of generated) {
    const path = resolve(output, name);
    await mkdir(dirname(path), {recursive: true});
    await writeFile(path, text);
  }
  console.log('Generated API from ' + inputs.length + ' OpenAPI inputs.');
}
